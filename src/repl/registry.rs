//! The one list of the shell's backslash commands.
//!
//! Help, the consistency tests and (later) completion and remote mode read this
//! table; the parser in `commands.rs` stays hand-written, and a test checks that
//! every example here parses and that every command word the parser accepts is
//! listed here. A command added to the parser without an entry fails that test,
//! so the help can no longer drift from what the shell accepts.

/// The help category a command belongs to (`\h <category>`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Category {
    /// Quitting, help, display, information.
    Basics,
    /// Tables, views, indexes.
    Schema,
    /// Database branches.
    Branching,
    /// Snapshots and historical queries.
    TimeTravel,
    /// Vector stores.
    Vectors,
    /// Document collections and RAG.
    Documents,
    /// Agent sessions.
    Agents,
    /// AI helpers.
    Ai,
    /// Multi-tenancy.
    Tenants,
    /// Configuration, performance, accounts.
    Settings,
}

impl Category {
    /// The word that selects it in `\h <word>`.
    pub fn word(self) -> &'static str {
        match self {
            Self::Basics => "basics",
            Self::Schema => "schema",
            Self::Branching => "branching",
            Self::TimeTravel => "time-travel",
            Self::Vectors => "vectors",
            Self::Documents => "documents",
            Self::Agents => "agents",
            Self::Ai => "ai",
            Self::Tenants => "tenants",
            Self::Settings => "settings",
        }
    }

    /// Every category, in help order.
    pub const ALL: [Category; 10] = [
        Self::Basics,
        Self::Schema,
        Self::Branching,
        Self::TimeTravel,
        Self::Vectors,
        Self::Documents,
        Self::Agents,
        Self::Ai,
        Self::Tenants,
        Self::Settings,
    ];
}

/// One backslash command.
#[derive(Debug, Clone, Copy)]
pub struct CommandSpec {
    /// The command as typed, up to its first argument: `\d`, `\tenant create`.
    pub name: &'static str,
    /// Other spellings of the name: `\quit`, `\?`.
    pub aliases: &'static [&'static str],
    /// The arguments: `<table>`, `[plan]`.
    pub args: &'static str,
    /// One line of what it does.
    pub summary: &'static str,
    /// The help category.
    pub category: Category,
    /// The part of the category's help it is printed under.
    pub section: &'static str,
    /// Lines that run it; each must parse.
    pub examples: &'static [&'static str],
    /// Help prints the examples (for the others they only serve the tests).
    pub show_examples: bool,
    /// It reads the database handle directly, so a shell connected to a server
    /// (remote mode) must refuse it.
    pub local_only: bool,
    /// Accepted but not listed in help.
    pub hidden: bool,
}

impl CommandSpec {
    /// How help writes it: name, arguments, then the aliases.
    pub fn display_form(&self) -> String {
        let mut form = self.name.to_string();
        if !self.args.is_empty() {
            form.push(' ');
            form.push_str(self.args);
        }
        for alias in self.aliases {
            form.push_str(", ");
            form.push_str(alias);
        }
        form
    }

    /// The first word of the name and of every alias, without the backslash.
    pub fn first_words(&self) -> impl Iterator<Item = &'static str> + '_ {
        std::iter::once(self.name)
            .chain(self.aliases.iter().copied())
            .filter_map(|spelling| spelling.strip_prefix('\\'))
            .filter_map(|spelling| spelling.split_whitespace().next())
    }
}

/// Every command.
pub fn all() -> &'static [CommandSpec] {
    COMMANDS
}

/// The commands of one part of one category's help, in table order, hidden ones left out.
pub fn entries(category: Category, section: &str) -> impl Iterator<Item = &'static CommandSpec> + '_ {
    COMMANDS
        .iter()
        .filter(move |spec| spec.category == category && spec.section == section && !spec.hidden)
}

/// The commands of a category, hidden ones left out.
pub fn in_category(category: Category) -> impl Iterator<Item = &'static CommandSpec> {
    COMMANDS
        .iter()
        .filter(move |spec| spec.category == category && !spec.hidden)
}

/// Every first word a command can start with (without the backslash), sorted
/// and without repeats: what completion offers after a backslash.
pub fn command_words() -> Vec<&'static str> {
    let mut words: Vec<&'static str> = COMMANDS.iter().flat_map(CommandSpec::first_words).collect();
    words.sort_unstable();
    words.dedup();
    words
}

/// The entry for a command word (`d`, `quit`, `tenant`), if any.
pub fn find(word: &str) -> Option<&'static CommandSpec> {
    COMMANDS.iter().find(|spec| spec.first_words().any(|w| w == word))
}

/// Split the text after the backslash into arguments the way a shell does:
/// words are separated by white space, single and double quotes group (and are
/// removed), and a backslash outside single quotes escapes the next character.
///
/// # Errors
///
/// A message when a quote is left open or the text ends in a backslash.
pub fn split_args(input: &str) -> Result<Vec<String>, String> {
    let mut args = Vec::new();
    let mut current = String::new();
    let mut started = false;
    let mut quote: Option<char> = None;
    let mut chars = input.chars();
    while let Some(ch) = chars.next() {
        match quote {
            Some(q) if ch == q => quote = None,
            Some('\'') => current.push(ch),
            Some(_) if ch == '\\' => match chars.next() {
                Some(next) => current.push(next),
                None => return Err("a backslash ends the line".to_string()),
            },
            Some(_) => current.push(ch),
            None => match ch {
                '\'' | '"' => {
                    quote = Some(ch);
                    started = true;
                }
                '\\' => match chars.next() {
                    Some(next) => {
                        current.push(next);
                        started = true;
                    }
                    None => return Err("a backslash ends the line".to_string()),
                },
                c if c.is_whitespace() => {
                    if started {
                        args.push(std::mem::take(&mut current));
                        started = false;
                    }
                }
                c => {
                    current.push(c);
                    started = true;
                }
            },
        }
    }
    if let Some(q) = quote {
        return Err(format!("unterminated {q} quote"));
    }
    if started {
        args.push(current);
    }
    Ok(args)
}

